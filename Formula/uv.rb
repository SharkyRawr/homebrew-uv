class Uv < Formula
  desc "Extremely fast Python package installer and resolver, written in Rust"
  homepage "https://docs.astral.sh/uv/"
  url "https://github.com/astral-sh/uv/archive/refs/tags/0.13.10.tar.gz"
  sha256 "70ca6903100629c77f0539ed2944dcada30d05448eee8bae51a2b28c36b02ca9"
  license any_of: ["Apache-2.0", "MIT"]
  compatibility_version 1
  head "https://github.com/astral-sh/uv.git", branch: "main"

  bottle do
    root_url "https://github.com/SharkyRawr/homebrew-uv/releases/download/bottles-0.13.10"
    sha256 cellar: :any_skip_relocation, arm64_golden_gate: "9cd0bcfcd11eba147f95b6d569488527f91b4e5d5df8d693330a9699e609e98e"
    sha256 cellar: :any_skip_relocation, arm64_tahoe:       "4b16242ace747384a87ce41b0fbc796e54cc5d7eff3db9fe9005d9bb8cbae0ff"
    sha256 cellar: :any,                 x86_64_linux:      "aef728ee9de94a3e39e2702b77cd6be25864a6cb973256e5a5aa53e7fa17f139"
  end

  depends_on "pkgconf" => :build
  depends_on "rust" => :build

  uses_from_macos "python" => :test
  uses_from_macos "bzip2"
  uses_from_macos "xz"

  # downloads crates on install and wheels in test
  deny_network_access! :postinstall

  def install
    ENV["UV_COMMIT_HASH"] = ENV["UV_COMMIT_SHORT_HASH"] = tap.user
    ENV["UV_COMMIT_DATE"] = time.strftime("%F")
    # See: https://github.com/astral-sh/uv/issues/15401
    ENV["JEMALLOC_SYS_WITH_LG_PAGE"] = "16" if Hardware::CPU.arm? && OS.linux?
    cargo_target = ENV["HOMEBREW_UV_CARGO_TARGET_DIR"]
    ENV["CARGO_TARGET_DIR"] = cargo_target if cargo_target
    system "cargo", "install", *std_cargo_args(path: "crates/uv")
    # Keep third-party dependencies in CI, but always rebuild uv's workspace from the requested source.
    system "cargo", "clean", "--workspace", "--release", "--frozen" if cargo_target
    generate_completions_from_executable(bin/"uv", "generate-shell-completion")
    generate_completions_from_executable(bin/"uvx", "--generate-shell-completion")
  end

  test do
    (testpath/"requirements.in").write <<~REQUIREMENTS
      requests
    REQUIREMENTS

    compiled = shell_output("#{bin}/uv pip compile -q requirements.in")
    assert_match "This file was autogenerated by uv", compiled
    assert_match "# via requests", compiled

    assert_match "ruff 0.5.1", shell_output("#{bin}/uvx -q ruff@0.5.1 --version")
  end
end
